#!/usr/bin/env python3
"""Data Division A ledger: sum the play-table shard sidecars into docs/datasources/pbp-ledger.{json,md}.

Serves: EXP-1000 / EXP-097 (real tokens landed, honest split). Owner: Data Planner A.

    python scripts/pbp/ledger.py DIR [DIR ...] [--write]      # DIR = a Kaggle output folder holding */*.parquet.json

Counts only what landed (a shard with its sidecar). Every row of the ledger is NEW information (real events);
derived per-play state and tokenizer-v2 rich fields are counted by lane 1, synthetic/augmentation in data-ledger.md.
A shard without a license line, or a plan-B shard without the personal-use tag, fails --check.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from pbp.schema import PERSONAL  # noqa: E402

OUT_JSON = ROOT / "docs/datasources/pbp-ledger.json"
OUT_MD = ROOT / "docs/datasources/pbp-ledger.md"


def collect(dirs: list[Path]) -> list[dict]:
    seen, rows = set(), []
    for d in dirs:
        for p in sorted(d.rglob("*.parquet.json")):
            m = json.loads(p.read_text())
            key = (m.get("source"), m.get("league"), str(m.get("season")), bool(m.get("playoffs")))
            if key in seen:      # the same shard from two runs counts once
                continue
            seen.add(key)
            rows.append(m)
    return rows


def problems(rows: list[dict]) -> list[str]:
    errs = []
    for m in rows:
        name = f"{m.get('source')}/{m.get('league')}/{m.get('season')}"
        if not m.get("license"):
            errs.append(f"{name}: no license line")
        if m.get("data_plan") == "B" and m.get("tag") != PERSONAL:
            errs.append(f"{name}: plan-B shard without the personal-use tag")
    return errs


def summarize(rows: list[dict]) -> dict:
    by = defaultdict(lambda: {"shards": 0, "games": 0, "events": 0, "v1_tokens": 0, "bytes": 0, "seasons": set(),
                              "license": "", "tag": ""})
    for m in rows:
        b = by[(m["source"], m["league"])]
        b["shards"] += 1
        for k in ("games", "events", "v1_tokens", "bytes"):
            b[k] += int(m.get(k) or 0)
        b["seasons"].add(int(m["season"]))
        b["license"], b["tag"] = m.get("license", ""), m.get("tag", "")
        b["kind"] = ("tracking" if "tracking" in str(m.get("rows_are", "")) or str(m.get("source", "")).endswith("_extra")
                     else "events")
    out = []
    for (src, lg), b in sorted(by.items(), key=lambda kv: -kv[1]["v1_tokens"]):
        s = sorted(b.pop("seasons"))
        out.append({"source": src, "league": lg, "seasons": f"{s[0]}-{s[-1]}" if s else "", **b})
    keys = ("shards", "games", "events", "v1_tokens", "bytes")
    tot = {k: sum(r[k] for r in out if r["kind"] == "events") for k in keys}
    trk = {k: sum(r[k] for r in out if r["kind"] == "tracking") for k in keys}
    return {"rows": out, "total": tot, "tracking": trk}


def render(s: dict) -> str:
    lines = ["# Data Division A: play-by-play landed", "",
             "Generated by `python scripts/pbp/ledger.py <kaggle output> --write`. Do not edit by hand.", "",
             "Only shards that landed in the private Kaggle dataset count. Every token here is **new information** "
             "(real events, vocab v1 = 6 tokens per event + 4 per game). Tokenizer v2's derived per-play fields are "
             "counted by lane 1 and never here; synthetic and augmentation go in data-ledger.md (capped at 3x real).",
             "", "| Source | League | Seasons | Games | Events | v1 tokens (M) | GB | Tag | License line |",
             "|---|---|---|---:|---:|---:|---:|---|---|"]
    for r in s["rows"]:
        lines.append(f"| {r['source']} | {r['league']} | {r['seasons']} | {r['games']:,} | {r['events']:,} | "
                     f"{r['v1_tokens'] / 1e6:.1f} | {r['bytes'] / 1e9:.2f} | {r['tag'] or '-'} | {r['license']} |")
    t = s["total"]
    k = s.get("tracking") or {}
    lines += [f"| **Total events** | | | | {t['games']:,} | {t['events']:,} | {t['v1_tokens'] / 1e6:.1f} | "
              f"{t['bytes'] / 1e9:.2f} | | |"]
    if k.get("shards"):
        lines += [f"| **Total tracking** | | | | {k['games']:,} | {k['events']:,} | {k['v1_tokens'] / 1e6:.1f} | "
                  f"{k['bytes'] / 1e9:.2f} | | |"]
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dirs", nargs="*", type=Path)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    rows = collect(a.dirs)
    errs = problems(rows)
    for e in errs:
        print("FAIL", e)
    s = summarize(rows)
    print(render(s))
    if a.write and not errs:
        OUT_JSON.write_text(json.dumps(s, indent=1) + "\n")
        OUT_MD.write_text(render(s))
    return 1 if errs else 0


if __name__ == "__main__":
    raise SystemExit(main())
