"""Generate docs/agents/INDEX.md from report front matter, and check the organization standard (docs/STANDARD.md).

    python scripts/doc_index.py            # rewrite docs/agents/INDEX.md
    python scripts/doc_index.py --check    # CI: exit 1 if a report breaks the standard or the index is stale

Why: Nick, 2026-11-08: "maintain organization to a new standard ... it will become standard across the code base".
A hand-kept index drifts; this one is generated from each report's front matter.
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGENTS = ROOT / "docs" / "agents"
INDEX = AGENTS / "INDEX.md"
REQUIRED = ("id", "title", "date", "stream", "author", "status", "sources", "verified", "affects", "gate")
STATUSES = {"draft", "reviewed", "adopted", "rejected", "superseded"}
STREAMS = {"process", "rules", "context", "locked-results", "harness", "training", "data", "audit", "planner"}
SKIP = {"INDEX.md", "README.md", "log.md", "catalog.md"}


def front_matter(text: str) -> dict | None:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    import yaml
    try:
        d = yaml.safe_load(m.group(1))
    except Exception:
        return None
    return d if isinstance(d, dict) else None


# Reports from before the standard: indexed, but they keep their paths (other docs link to them).
LEGACY = ("docs/research/2026-11-08", "docs/audits")


def reports(root: Path | None = None) -> list[Path]:
    root = AGENTS if root is None else root
    out = [p for p in root.rglob("*.md") if p.name not in SKIP]
    for d in LEGACY:
        out += [p for p in (ROOT / d).rglob("*.md") if p.name not in SKIP and p.name[:10] != "REVIEW_BRI"]
    return sorted(out)


def problems(paths: list[Path]) -> tuple[list[dict], list[str]]:
    rows, errs, ids = [], [], {}
    for p in paths:
        rel = p.relative_to(ROOT).as_posix()
        fm = front_matter(p.read_text())
        if fm is None:
            errs.append(f"{rel}: no front matter (docs/STANDARD.md section 2)")
            continue
        missing = [k for k in REQUIRED if k not in fm]
        if missing:
            errs.append(f"{rel}: missing {missing}")
        if fm.get("status") not in STATUSES:
            errs.append(f"{rel}: status {fm.get('status')!r} not in {sorted(STATUSES)}")
        if fm.get("stream") not in STREAMS:
            errs.append(f"{rel}: stream {fm.get('stream')!r} not in {sorted(STREAMS)}")
        legacy = any(rel.startswith(d) for d in LEGACY)
        if not legacy and not re.fullmatch(r"\d{4}-\d{2}-\d{2}-[a-z0-9-]+\.md", p.name):
            errs.append(f"{rel}: file name must be YYYY-MM-DD-slug.md")
        rid = str(fm.get("id", ""))
        if rid in ids:
            errs.append(f"{rel}: id {rid} also used by {ids[rid]}")
        ids[rid] = rel
        for g in fm.get("gate") or []:
            if not str(g).startswith(rid + "-"):
                errs.append(f"{rel}: gate item {g} must start with {rid}-")
        try:
            if int(fm.get("verified", 0)) > int(fm.get("sources", 0)):
                errs.append(f"{rel}: verified > sources")
        except (TypeError, ValueError):
            errs.append(f"{rel}: sources/verified must be numbers")
        rows.append({**fm, "path": os.path.relpath(p, AGENTS).replace(os.sep, "/")})
    return rows, errs


def render(rows: list[dict]) -> str:
    out = ["# Agent reports index", "",
           "Generated by `python scripts/doc_index.py` from each report's front matter. Do not edit by hand.",
           "Standard: [docs/STANDARD.md](../STANDARD.md). Plan and process gate: [docs/PLAN.md](../PLAN.md).", ""]
    for stream in sorted({r["stream"] for r in rows}):
        out += [f"## {stream}", "", "| id | date | title | status | sources (verified) | gate items |", "|---|---|---|---|---|---|"]
        for r in sorted((r for r in rows if r["stream"] == stream), key=lambda r: (str(r["date"]), str(r["id"]))):
            gate = ", ".join(map(str, r.get("gate") or [])) or "-"
            out.append(f"| {r['id']} | {r['date']} | [{r['title']}]({r['path']}) | {r['status']} | "
                       f"{r.get('sources', '?')} ({r.get('verified', '?')}) | {gate} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    rows, errs = problems(reports())
    text = render(rows)
    if "--check" in argv:
        if not INDEX.exists() or INDEX.read_text() != text:
            errs.append("docs/agents/INDEX.md is stale: run python scripts/doc_index.py")
        for e in errs:
            print(e)
        print("doc standard ok" if not errs else f"{len(errs)} problem(s)")
        return 1 if errs else 0
    INDEX.write_text(text)
    for e in errs:
        print("WARN", e)
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(rows)} reports)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
