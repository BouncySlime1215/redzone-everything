"""Write docs/state-machines.md from the specs in redzone/machines/ (or --check that it is current).

    python scripts/state_machines.py           # regenerate
    python scripts/state_machines.py --check   # CI: exit 1 if the doc is stale
Why: Writes docs/state-machines.md from redzone/machines specs (docstring, state machines commit).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from redzone import fsm  # noqa: E402
import redzone.machines as machines  # noqa: E402

OUT = ROOT / "docs" / "state-machines.md"


def render() -> str:
    specs = sorted(machines.ALL.values(), key=lambda s: (s.owner.split(".")[0], s.name))
    specs = [s for s in specs if not s.name.startswith("test_")]
    out = ["# State machines", "",
           "Generated by `python scripts/state_machines.py` from `redzone/machines/`. Do not edit by hand.",
           "", "Rules: [redzone/fsm.py](../redzone/fsm.py). Live view: `GET /api/machines`.",
           "Only `Machine.to()` moves a state; an undeclared move fails tests and logs a warning live.", "",
           "| Machine | Owner | What it tracks | States |", "|---|---|---|---|"]
    for s in specs:
        out.append(f"| [{s.name}](#{s.name}) | `{s.owner}` | {s.doc} | {len(s.states)} |")
    for s in specs:
        out += ["", f"## {s.name}", "", f"Owner: `{s.owner}`{' (one per key)' if s.keyed else ''}. {s.doc}", "",
                "| State | Meaning | Can move to |", "|---|---|---|"]
        for st, meaning in s.states.items():
            to = ", ".join("any" if t == fsm.ANY else t for t in s.edges.get(st, ())) or "-"
            mark = " (initial)" if st == s.initial else ""
            out.append(f"| `{st}`{mark} | {meaning} | {to} |")
        out += ["", "```mermaid", fsm.mermaid(s), "```"]
    return "\n".join(out) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/state-machines.md is stale: run python scripts/state_machines.py")
            return 1
        print("docs/state-machines.md is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
