#!/usr/bin/env python3
"""Data scout ledger: check docs/datasources/scout.json and render scout-ledger.md, ranked by new information per GB.

Serves: EXP-097 (Nick 11:35 PM Nov 4: 100x more data sources, scout loop). Owner: the scout thread writes
scout.json each cycle; the owning crew (A-F) flips status to pulling/done and replaces estimates with factory counts.
Light: stdlib only, reads one small JSON file.

    python scripts/scout_ledger.py            # check + rewrite docs/datasources/scout-ledger.md
    python scripts/scout_ledger.py --check    # check only, exit 1 on a problem (CI-safe)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "datasources" / "scout.json"
OUT = ROOT / "docs" / "datasources" / "scout-ledger.md"
VERDICTS = ("green", "yellow", "yellow-B")          # red never sits in "sources"
STATUSES = ("probe", "hold", "parked", "needs-nick", "ready-for-lane1", "pulling", "done", "dropped")
REAL_DONE = ("pulling", "done")
KINDS = ("events", "context-new", "derived")
NEEDED = ("id", "kind", "cycle", "priority", "name", "access", "verdict", "license", "est_tokens_m", "novelty",
          "raw_gb", "status", "owner", "needs_nick")


def score(s: dict) -> float:
    """New tokens (M) x novelty per raw GB downloaded."""
    return s["est_tokens_m"] * s["novelty"] / max(s["raw_gb"], 0.05)


def check(d: dict) -> list[str]:
    errs, seen = [], set()
    for s in d.get("sources", []):
        sid = s.get("id", "?")
        for k in NEEDED:
            if k not in s or s[k] in ("", None) and k != "needs_nick":
                errs.append(f"{sid}: missing {k}")
        if sid in seen:
            errs.append(f"{sid}: duplicate id")
        seen.add(sid)
        if s.get("verdict") not in VERDICTS:
            errs.append(f"{sid}: verdict {s.get('verdict')!r} not in {VERDICTS} (red goes in red_found)")
        if s.get("kind") not in KINDS:
            errs.append(f"{sid}: kind {s.get('kind')!r} not in {KINDS}")
        if s.get("kind") == "derived" and s.get("novelty") != 0:
            errs.append(f"{sid}: derived tokens add no new knowledge, so novelty must be 0")
        if s.get("status") not in STATUSES:
            errs.append(f"{sid}: status {s.get('status')!r} not in {STATUSES}")
        if s.get("verdict") == "yellow-B" and "plan B" not in s.get("license", "") and "personal use" not in s.get("license", ""):
            errs.append(f"{sid}: yellow-B license line must say it is plan B / personal use")
        if s.get("status") == "needs-nick" and s.get("needs_nick") in ("", "none"):
            errs.append(f"{sid}: status needs-nick but needs_nick says none")
    return errs


def render(d: dict) -> str:
    allsrc = d["sources"]
    src = sorted([s for s in allsrc if s["kind"] != "derived"], key=score, reverse=True)
    der = [s for s in allsrc if s["kind"] == "derived"]
    tag = d["personal_use_tag"]
    L = ["# Data scout ledger", "",
         "Generated by `python scripts/scout_ledger.py` from [scout.json](scout.json). Do not edit by hand.", "",
         d["about"], "",
         f"- Tokens: {d['token_rule']}", f"- Rank: {d['info_per_gb_rule']}",
         f"- Every **yellow-B** row is tagged **\"{tag}\"** on the dataset and on any model trained on it; "
         "the company version retrains on green/yellow only.",
         "- Guardrails: public endpoints only; no logins, paywalls, CAPTCHAs or bot-block bypasses; robots and "
         "rate limits respected; derived numbers only from articles or pages; no broadcast video or audio; "
         "any paid feed needs Nick's OK; jobs run on Kaggle/Colab, never the Mac.", "",
         "## Ranked sources", "",
         "Derived rows are listed after the ranking and never count toward new information.", "",
         "| Rank | Source | Pri | Kind | Verdict | Est. tokens (M) | Raw GB | Info/GB | Status | Owner | Nick action | License line |",
         "|---:|---|---:|---|---|---:|---:|---:|---|---|---|---|"]
    for i, s in enumerate(src, 1):
        v = s["verdict"] + (f" ({tag})" if s["verdict"] == "yellow-B" else "")
        L.append(f"| {i} | {s['name']} | {s['priority']} | {s['kind']} | {v} | {s['est_tokens_m']:g} | {s['raw_gb']:g} | "
                 f"{score(s):.1f} | {s['status']} | {s['owner']} | {s['needs_nick']} | {s['license']} |")
    L += ["", "## Derived (no new knowledge)", "", "| Source | Est. tokens (M) | What |", "|---|---:|---|"]
    L += [f"| {s['name']} | {s['est_tokens_m']:g} | {s['access']} |" for s in der]
    L += ["", "## Totals (honest split)", "", "| Kind | Sources | Est. tokens (M) |", "|---|---:|---:|"]
    for k in KINDS:
        rows = [s for s in allsrc if s["kind"] == k]
        L.append(f"| {k} | {len(rows)} | {sum(s['est_tokens_m'] for s in rows):g} |")
    L.append(f"| **New information (events + context-new)** | {len(src)} | {sum(s['est_tokens_m'] for s in src):g} |")
    L += ["", "## New-information totals by status and verdict", "", "| Bucket | Sources | Est. tokens (M) |", "|---|---:|---:|"]
    buckets = [("Ready for lane 1", lambda s: s["status"] == "ready-for-lane1"),
               ("Pulling or done (real)", lambda s: s["status"] in REAL_DONE),
               ("Probe / hold (scout)", lambda s: s["status"] in ("probe", "hold")),
               ("Needs Nick", lambda s: s["status"] == "needs-nick"),
               ("Parked", lambda s: s["status"] == "parked")]
    for name, f in buckets:
        rows = [s for s in src if f(s)]
        L.append(f"| {name} | {len(rows)} | {sum(s['est_tokens_m'] for s in rows):g} |")
    for v in VERDICTS:
        rows = [s for s in src if s["verdict"] == v]
        L.append(f"| Verdict {v} | {len(rows)} | {sum(s['est_tokens_m'] for s in rows):g} |")
    L.append(f"| **All new-information candidates** | {len(src)} | {sum(s['est_tokens_m'] for s in src):g} |")
    cycles = sorted({s["cycle"] for s in src})
    L += ["", "## Growth by cycle (candidates added, cumulative)", "", "| Cycle | Added | Est. tokens added (M) | Cumulative (M) |",
          "|---|---:|---:|---:|"]
    cum = 0.0
    for c in cycles:
        rows = [s for s in src if s["cycle"] == c]
        add = sum(s["est_tokens_m"] for s in rows)
        cum += add
        L.append(f"| {c} | {len(rows)} | {add:g} | {cum:g} |")
    L += ["", "## Why each source", ""]
    for s in src:
        L.append(f"- **{s['name']}** ({s.get('sports', '')}, {s.get('years', '')}): {s.get('why', '')} Access: {s['access']}.")
    L += ["", "## Found and rejected (red)", "", "| Source | Why not |", "|---|---|"]
    L += [f"| {r['name']} | {r['why']} |" for r in d.get("red_found", [])]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", type=Path, default=SRC)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true", help="validate only")
    a = ap.parse_args(argv)
    d = json.loads(a.src.read_text())
    errs = check(d)
    for e in errs:
        print("scout.json:", e, file=sys.stderr)
    if errs:
        return 1
    md = render(d)
    if a.check:
        if a.out.exists() and a.out.read_text() != md:
            print(f"{a.out} is stale: run python scripts/scout_ledger.py", file=sys.stderr)
            return 1
        return 0
    a.out.write_text(md)
    new = sum(s["est_tokens_m"] for s in d["sources"] if s["kind"] != "derived")
    der = sum(s["est_tokens_m"] for s in d["sources"] if s["kind"] == "derived")
    print(f"wrote {a.out} ({len(d['sources'])} sources; new-information {new:g}M, derived {der:g}M est. tokens)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
