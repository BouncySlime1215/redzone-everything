#!/usr/bin/env python3
"""The city map: docs/citymap.md (for people) and docs/citymap.json (for CI and northstar.py), generated
from the code's imports and redzone/contracts/map.py. Nick, Nov 4 3:40 PM: one connected system.

    python scripts/citymap.py            # write both
    python scripts/citymap.py --check    # exit 1 if either file is out of date (nothing written)

northstar.yml regenerates both on every integration/next push. The contract checks themselves (and
the baseline of known violations) are scripts/contract_check.py.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from redzone.contracts import map as M  # noqa: E402
from redzone.lab import citymap as C  # noqa: E402

MD, JS = ROOT / "docs" / "citymap.md", ROOT / "docs" / "citymap.json"


def area(mod: str, pkg: bool = False) -> str:
    """The district a module lives in: its package (redzone, redzone.tuners, redzone.lab.night, agent.kaggle)."""
    if pkg:
        return mod
    parts = mod.split(".")
    if len(parts) >= 4 and parts[1] == "lab":
        return ".".join(parts[:3])
    return ".".join(parts[:2]) if len(parts) >= 3 else parts[0]


def payload(m: dict, v: list[dict]) -> dict:
    pub = C.public(m)
    return {"generated_by": "scripts/citymap.py", "modules": pub["modules"], "edges": pub["edges"],
            "violations": [{k: x[k] for k in ("rule", "where", "module", "detail", "owner", "lane", "key")} for x in v],
            "counts": dict(Counter(x["rule"] for x in v)),
            "json_loads_sites": sum(x.get("json_loads", 0) for x in m["modules"].values())}


def render(m: dict, v: list[dict]) -> str:
    mods = m["modules"]
    live = C.reachable(m)

    def ar(name: str) -> str:
        return area(name, mods[name]["path"].endswith("__init__.py"))
    by_area: dict[str, list[str]] = defaultdict(list)
    for name in sorted(mods):
        by_area[ar(name)].append(name)
    links = Counter((ar(a), ar(b)) for a, b in m["edges"] if ar(a) != ar(b))
    vio = defaultdict(list)
    for x in v:
        vio[x["module"]].append(x)
    md = ["# City map", "",
          "Generated by `scripts/citymap.py` from the imports and `redzone/contracts/map.py` (do not edit by hand; "
          "northstar.yml regenerates it). Every module, what it reads, who uses it, who owns it, and the contract "
          "checks of `scripts/contract_check.py` (CI).", "",
          f"**{len(mods)} modules, {sum(x['lines'] for x in mods.values()):,} lines, {len(m['edges'])} import edges. "
          f"Contract violations: {len(v)}** "
          f"({', '.join(f'{k} {n}' for k, n in sorted(Counter(x['rule'] for x in v).items())) or 'none'}). "
          f"`json.loads` call sites: {sum(x.get('json_loads', 0) for x in mods.values())}.", "",
          "## Districts", "",
          "Each box is a package; an arrow is one district importing another (the number is how many import edges).", "",
          "```mermaid", "graph LR"]
    ids = {a: f"d{i}" for i, a in enumerate(sorted(by_area))}
    for a in sorted(by_area):
        owners = Counter(mods[x]["owner"] for x in by_area[a]).most_common(1)[0][0]
        md.append(f'  {ids[a]}["{a}<br/>{len(by_area[a])} modules, {owners}"]')
    for (a, b), n in sorted(links.items()):
        md.append(f"  {ids[a]} -->|{n}| {ids[b]}")
    md += ["```", "", "## Contract violations", ""]
    if not v:
        md += ["None.", ""]
    else:
        md += ["| rule | where | owner (lane) | what |", "|---|---|---|---|"]
        md += [f"| {x['rule']} | `{x['where']}` | {x['owner']} ({x['lane'] or '–'}) | {x['detail']} |"
               for x in sorted(v, key=lambda x: (x["rule"], x["where"]))]
        md.append("")
    md += ["## Modules", "",
           "Reads: the modules it imports, the config sections it reads (`cfg.get(\"section.key\")`) and data files it names. "
           "Used by: modules of ours that import it (+ scripts, tests). ⚠ = a contract violation, ✝ = no entry point reaches it.", ""]
    for a in sorted(by_area):
        md += [f"### {a}", "", "| module | owner | lines | reads | config | data | used by |", "|---|---|---:|---|---|---|---|"]
        for name in by_area[a]:
            x = mods[name]
            short = name.split(".")[-1] if name != a else name
            flag = (" ⚠" if vio.get(name) else "") + ("" if name in live or x["path"].endswith("__init__.py") else " ✝")
            reads = ", ".join(i.removeprefix("redzone.") for i in x["imports"]) or "–"
            used = len(x["used_by"])
            ub = f"{used} modules" if used > 4 else (", ".join(u.removeprefix("redzone.") for u in x["used_by"]) or "–")
            extra = [f"{len(x['used_by_scripts'])} scripts"] if x["used_by_scripts"] else []
            extra += [f"{x['used_by_tests']} tests"] if x.get("used_by_tests") else []
            md.append(f"| `{short}`{flag} | {x['owner']} | {x['lines']} | {reads} | {', '.join(x['config']) or '–'} | "
                      f"{', '.join(x['data']) or '–'} | {ub}{' (+' + ', '.join(extra) + ')' if extra else ''} |")
        md.append("")
    md += ["## How to read and change it", "",
           "- Owners and lanes: `redzone/contracts/map.py` OWNERS / LANE (from docs/architecture.md §4).",
           "- A contract rule changes in `redzone/contracts/map.py` only, with a docs/memory/decisions.md line.",
           "- Known violations are the baseline in `docs/contract-baseline.json`: CI fails on a new one; a fixed one is "
           "dropped with `python scripts/contract_check.py --update-baseline`.", ""]
    return "\n".join(md)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/citymap.{md,json} are out of date")
    a = ap.parse_args(argv)
    m = C.build(ROOT)
    v = C.violations(m)
    md, js = render(m, v), json.dumps(payload(m, v), indent=1, sort_keys=True) + "\n"
    if a.check:
        stale = [p.name for p, t in ((MD, md), (JS, js)) if not p.exists() or p.read_text() != t]
        print("city map up to date" if not stale else f"out of date: {', '.join(stale)} (run python scripts/citymap.py)")
        return 1 if stale else 0
    MD.write_text(md)
    JS.write_text(js)
    print(f"{MD.relative_to(ROOT)}: {len(m['modules'])} modules, {len(m['edges'])} edges, {len(v)} contract violations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
